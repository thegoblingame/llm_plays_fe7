#!/usr/bin/env python3
"""Build required_units.json (what fe7_prep_select_units reads) from deployment_source.json.

    usage:  python3 scripts/build_required_units.py

deployment_source.json is the human-facing source: one row per chapter, mode and difficulty,
keyed by chapter names and on-screen numbers. The tool cannot read either of those. It reads
the game's CHAPTER INDEX (0x0202BC06) and MODE (0x0202BC13), so this script adds the one
thing the source lacks — the index for each chapter — and regroups the rows by it.

Edit deployment_source.json, never required_units.json, then rerun this.

THE INDEX TABLE. FE7 numbers chapters in one sequence: Lyn's tale, then the main story, with
each mode-exclusive chapter (Talons Alight, Valorous Roland, The Berserker...) taking its own
slot and a shared map keeping ONE index in both modes. The table below is that sequence
counted out. Four entries were read from real saves (VERIFIED); the rest are counted from
them. fe7_prep_select_units cross-checks every chapter at runtime: if the start tiles it
counts match neither difficulty's deployment_limit for the entry it picked, status says the
index mapping is probably wrong. When status shows a chapter whose name is right, add it to
VERIFIED with the evidence.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "deployment_source.json"
OUTPUT = ROOT / "required_units.json"
NAMES = ROOT / "overlay" / "names.json"

INDEX = {
    "siblings abroad": 0x07,
    "the black shadow": 0x08,
    "vortex of strategy": 0x09,
    "a grim reunion": 0x0A,
    "the distant plains": 0x0B,
    # 0x0C Taking Leave (E11), 0x0D Another Journey (H11), 0x0E Birds of a Feather,
    # 0x0F In Search of Truth, 0x10 The Peddler Merlinus — not in the source.
    "false friends": 0x11,
    "talons alight": 0x12,
    "noble lady of caelin": 0x13,
    "whereabouts unknown": 0x14,
    "the port of badon": 0x15,
    "pirate ship": 0x16,
    "the dread isle": 0x17,
    "imprisoner of magic": 0x18,
    "a glimpse in time": 0x19,
    "dragon's gate": 0x1A,
    "new resolve": 0x1B,
    "kinship's bond": 0x1C,
    "living legend": 0x1D,
    "genesis": 0x1E,
    "four-fanged offense (lloyd)": 0x1F,
    "four-fanged offense (linus)": 0x20,
    "crazed beast": 0x21,
    "unfulfilled heart": 0x22,
    "pale flower of darkness (kenneth)": 0x23,
    "pale flower of darkness (jerme)": 0x24,
    "battle before dawn": 0x25,
    "night of farewells": 0x26,
    "cog of destiny": 0x27,
    "valorous roland": 0x28,
    "the berserker": 0x29,
    "sands of time": 0x2A,
    "battle preparations": 0x2B,
    "victory or death": 0x2C,
    "the value of life": 0x2D,
    "light": 0x2E,
}

# Indices read from real save states, with the evidence. See RAM.md, "Chapter index".
VERIFIED = {
    0x17: "read on Grant's Dread Isle prep (objective 'Defeat Uhai', 12/12), 2026-11-08",
    0x25: "read on 28_hector_normal_tool.ss2 (Hector mode prep, 14/14), 2026-11-08",
    0x27: "read on a playthrough's s01_ch29_cog-of-destiny.ss, 2026-11-08",
    0x29: "read on 30_hector_normal_tool.ss2, 2026-11-08",
}

MODES = ("lyn", "eliwood", "hector")


def main() -> int:
    src = json.loads(SOURCE.read_text())
    known = {v["name"].lower() for v in json.loads(NAMES.read_text())["byChar"].values() if v.get("name")}

    problems: list[str] = []
    chapters: dict[int, dict] = {}
    for row in src["entries"]:
        name = row["chapter_name"].strip().lower()
        mode = row["mode"].strip().lower()
        if name not in INDEX:
            problems.append(f"{row['chapter_id']}: chapter name {name!r} has no index in INDEX")
            continue
        if mode not in MODES:
            problems.append(f"{row['chapter_id']}: unknown mode {mode!r}")
            continue
        for unit in row["required_units"]:
            if unit.lower() not in known:
                problems.append(f"{row['chapter_id']}: required unit {unit!r} is not in overlay/names.json")

        idx = INDEX[name]
        ch = chapters.setdefault(idx, {"names": {}, "required": {}, "limits": {}, "notes": set()})
        ch["names"][mode] = f"{mode} ch{row['chapter_number']}"
        ch["names"]["_title"] = name
        req = ch["required"].setdefault(mode, [])
        for unit in row["required_units"]:
            if unit.lower() not in [u.lower() for u in req]:
                req.append(unit)
        ch["limits"].setdefault(mode, {})[row["difficulty"].lower()] = row["deployment_limit"]
        if row.get("notes"):
            ch["notes"].add(row["notes"])

    if problems:
        print("NOT WRITTEN — fix deployment_source.json or the INDEX table:", file=sys.stderr)
        for p in problems:
            print("  - " + p, file=sys.stderr)
        return 1

    out = {
        "_readme": [
            "GENERATED by scripts/build_required_units.py from deployment_source.json. Do not edit by hand: edit the source and rerun.",
            "Read fresh by fe7_prep_select_units on every call. Keys are the game's chapter index (0x0202BC06); per-mode lists apply in that mode (0x0202BC13: 1 lyn, 2 eliwood, 3 hector).",
            "The tool always protects the current mode's lord as well, whatever is listed here, and protects every lord for a chapter or mode with no list.",
            "deployment_limit is a cross-check only: the tool counts start tiles itself and warns when the count matches neither difficulty.",
            "index_verified is the evidence that the index was read from a real save; otherwise it was counted (see the script).",
        ],
        "chapters": {},
    }
    for idx in sorted(chapters):
        ch = chapters[idx]
        title = ch["names"].pop("_title")
        label = " / ".join(ch["names"][m] for m in MODES if m in ch["names"])
        entry = {"name": f"{title} — {label}", "index_verified": VERIFIED.get(idx, False)}
        for m in MODES:
            if m in ch["required"]:
                entry[m] = ch["required"][m]
        entry["deployment_limit"] = ch["limits"]
        if ch["notes"]:
            entry["notes"] = " | ".join(sorted(ch["notes"]))
        out["chapters"][f"0x{idx:02X}"] = entry

    OUTPUT.write_text(json.dumps(out, indent=2, ensure_ascii=False) + "\n")
    print(f"wrote {OUTPUT} — {len(chapters)} chapters, {len(VERIFIED)} indices verified")
    return 0


if __name__ == "__main__":
    sys.exit(main())
